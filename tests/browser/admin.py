def check(value, name):
    if not value:
        raise AssertionError(name)
    checks.append(name)

def timer_row(page, timer_id):
    return page.locator('tbody tr').filter(has=page.locator('th code').filter(has_text=re.compile('^' + re.escape(timer_id) + '$')))

